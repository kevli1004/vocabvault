}

enum GradientPalette: String, Codable {
    case purple, teal, coral, amber, mint, rose, lavender

    var colors: [String] {
        switch self {
        case .purple:   return ["gradPurple1", "gradPurple2"]
        case .teal:     return ["gradTeal1",   "gradTeal2"]
        case .coral:    return ["gradCoral1",  "gradCoral2"]
        case .amber:    return ["gradAmber1",  "gradAmber2"]
        case .mint:     return ["gradMint1",   "gradMint2"]
        case .rose:     return ["gradRose1",   "gradRose2"]
        case .lavender: return ["gradLav1",    "gradLav2"]
        }
    }
}

// MARK: - Word Model

struct Word: Identifiable, Codable, Hashable {
    let id: String           // canonical key = lowercased word
    let word: String
    let definition: String
    let exampleSentence: String
    let synonyms: [String]
    let etymology: String
    let mnemonic: String
    let difficulty: Int      // 1 (easy) – 3 (hard)
    let category: WordCategory

    // Spaced-repetition / progress (mutable)
    var masteryLevel: MasteryLevel = .new
    var interval: Int        = 1    // days until next review
    var easeFactor: Double   = 2.5
    var repetitions: Int     = 0
    var nextReviewDate: Date = Date()
    var isFavorite: Bool     = false
    var timesCorrect: Int    = 0
    var timesIncorrect: Int  = 0

    var isDueForReview: Bool {
        nextReviewDate <= Date()
    }

    var accuracyRate: Double {
        let total = timesCorrect + timesIncorrect
        guard total > 0 else { return 0 }
        return Double(timesCorrect) / Double(total)
    }

    // Hashable / Equatable on id only
    func hash(into hasher: inout Hasher) { hasher.combine(id) }
    static func == (lhs: Word, rhs: Word) -> Bool { lhs.id == rhs.id }
}

