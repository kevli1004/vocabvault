// MARK: - Enums

enum WordCategory: String, CaseIterable, Codable {
    case character = "Character"
    case action = "Action"
    case description = "Description"
    case argument = "Argument"
    case change = "Change"
    case quantity = "Quantity"
    case society = "Society"

    var emoji: String {
        switch self {
        case .character:   return "🧠"
        case .action:      return "⚡"
        case .description: return "🎨"
        case .argument:    return "💬"
        case .change:      return "🔄"
        case .quantity:    return "📊"
        case .society:     return "🌍"
        }
    }

    var color: GradientPalette {
        switch self {
        case .character:   return .purple
        case .action:      return .teal
        case .description: return .coral
        case .argument:    return .amber
        case .change:      return .mint
        case .quantity:    return .rose
        case .society:     return .lavender
        }
    }
}

enum MasteryLevel: String, CaseIterable, Codable {
    case new       = "New"
    case learning  = "Learning"
    case reviewing = "Reviewing"
    case mastered  = "Mastered"

    var color: String {
        switch self {
        case .new:       return "masteryNew"
        case .learning:  return "masteryLearning"
        case .reviewing: return "masteryReviewing"
        case .mastered:  return "masteryMastered"
